import { expect } from '@playwright/test';
import { test } from './helpers/experiment-test';
import { createSyntheticFilledWeek } from './helpers/synthetic-schedule';

test('filled synthetic week supports grades, weekday events, gaps and substitutions', async ({ page, registerExperiment }) => {
  await page.setViewportSize({ width: 1920, height: 1080 });
  const experiment = await createSyntheticFilledWeek(page.request, registerExperiment);
  expect(experiment.payload.days).toEqual([0, 1, 2, 3, 4]);
  expect(experiment.payload.classes.length).toBeGreaterThanOrEqual(7);
  expect(experiment.payload.lessons.filter((lesson) => lesson.day === 0 && lesson.period === 0 && lesson.grade_scope === '9')).toHaveLength(3);
  expect(experiment.payload.lessons.map((lesson) => lesson.subject)).toEqual(expect.arrayContaining([
    'Экскурсия в музей', 'Нет урока', 'Математика · замена',
  ]));
  const lessons = experiment.payload.lessons as (Record<string, unknown> & { id: string; subject: string; day: number; period: number })[];
  const byId = (id: string) => lessons.find((lesson) => lesson.id === id);
  expect(lessons.filter((lesson) => lesson.id.startsWith('e2e-english-56-'))).toHaveLength(2);
  const electives = lessons.filter((lesson) => lesson.id.startsWith('e2e-elective-'));
  expect(electives).toHaveLength(4);
  expect(new Set(electives.map((lesson) => `${lesson.day}:${lesson.period}`))).toEqual(new Set(['1:0']));
  expect(new Set(electives.map((lesson) => lesson.groupId))).toEqual(new Set(experiment.electiveGroupIds));
  expect(new Set(lessons.filter((lesson) => lesson.id.startsWith('e2e-english-56-')).map((lesson) => lesson.groupId))).toEqual(new Set(experiment.englishGroupIds));
  expect(byId('e2e-digital-78')?.subject).toContain('7–8');
  expect(byId('e2e-digital-78')?.groupId).toBe(experiment.digitalGroupId);
  expect(byId('e2e-event')).toMatchObject({ kind: 'event', activityType: 'event', period: 4, start: '12:45', end: '14:25' });
  expect(byId('e2e-unknown-membership')).toMatchObject({ groupId: experiment.emptyGroupId, importError: false, needsClarification: false });
  const directory = await page.request.get('http://localhost:8011/api/admin/people?kind=student', { headers: { 'X-Dev-Auth': 'admin:1' } });
  expect(directory.ok()).toBeTruthy();
  const directoryStudents = (await directory.json()).items as { groups: { id: string }[] }[];
  const membersByGroup = new Map<string, number>();
  for (const student of directoryStudents) for (const group of student.groups || []) membersByGroup.set(String(group.id), (membersByGroup.get(String(group.id)) || 0) + 1);
  expect(membersByGroup.get(experiment.emptyGroupId) || 0).toBe(0);
  expect(experiment.englishGroupIds.map((id) => membersByGroup.get(id))).toEqual([2, 2]);
  expect(experiment.electiveGroupIds.map((id) => membersByGroup.get(id))).toEqual([2, 2, 2, 2]);
  expect(membersByGroup.get(experiment.digitalGroupId)).toBe(2);
  expect(byId('e2e-overlap-conflict-a')).toMatchObject({ day: 3, period: 0 });
  expect(byId('e2e-overlap-conflict-b')).toMatchObject({ day: 3, period: 0 });

  await page.goto('/admin/schedule/constructor?role=admin');
  await page.getByRole('group', { name: 'Разделы черновиков' }).getByRole('button', { name: /Тестовые/ }).click();
  await page.locator('.constructor-draft').filter({ hasText: experiment.name }).locator('.constructor-draft-open').click();
  await expect(page.locator('.constructor-head')).toHaveCount(7);
  await page.getByRole('button', { name: 'Фильтры' }).click();
  await page.getByRole('combobox', { name: 'Фильтр по классу' }).selectOption(experiment.grade5ClassId);
  await page.getByRole('button', { name: 'Пятница' }).click();
  await expect(page.locator('.constructor-card').filter({ hasText: 'Нет урока' })).toHaveCount(1);
  await expect(page.locator('.constructor-card').filter({ hasText: 'замена' })).toHaveCount(1);
  await page.getByRole('combobox', { name: 'Фильтр по классу' }).selectOption('');
  await page.getByRole('group', { name: 'Режим просмотра' }).getByRole('button', { name: 'Неделя' }).click();
  await expect(page.locator('.constructor-day-band')).toHaveCount(5);
  await expect(page.locator('.constructor-head')).toHaveCount(7);
  const lanes = page.locator('[data-cell="0:4"] .constructor-cell-lessons');
  await expect(lanes.locator('.constructor-card')).toHaveCount(3);
  await expect(lanes).toHaveCSS('grid-template-columns', /px .*px .*px/);
  const fitsViewport = await page.locator('.constructor-grid-wrap').evaluate((board) => board.scrollWidth <= board.clientWidth + 1);
  expect(fitsViewport).toBeTruthy();
  await page.locator('.constructor-issue-count').click();
  await expect(page.locator('.constructor-conflict-panel').getByRole('heading', { name: /^Неполные данные · \d+/ })).toBeVisible();
  await expect(page.locator('.constructor-unplaced')).toHaveCount(0);
  await page.getByRole('button', { name: 'Закрыть список проблем' }).click();
  await page.screenshot({ path: '.local-test/constructor-filled-week.png', fullPage: true });
  const periods = (await page.locator('.constructor-time').count()) / 5;
  const english = page.locator('[data-cell="0:0"] .constructor-card').filter({ hasText: 'Англ' }).first();
  await expect(page.locator('[data-cell="0:0"] .constructor-card').filter({ hasText: 'Англ' })).toHaveCount(2);
  await expect(page.locator('[data-cell="0:1"] .constructor-card').filter({ hasText: 'Англ' })).toHaveCount(2);
  const englishId = await english.getAttribute('data-lesson-id');
  await expect(page.locator(`[data-cell="0:1"] [data-lesson-id="${englishId}"]`)).toHaveCount(1);
  const electiveCell = page.locator(`[data-cell="${periods}:0"] .constructor-cell-lessons`);
  await expect(electiveCell.locator('.constructor-card')).toHaveCount(4);
  await expect(electiveCell).toHaveCSS('grid-template-columns', /px .*px/);
  await expect(page.locator(`[data-cell="${4 * periods + 4}:2"] [data-lesson-id="e2e-event"]`)).toHaveCount(1);
  await expect(page.locator(`[data-cell="${4 * periods + 5}:2"] [data-lesson-id="e2e-event"]`)).toHaveCount(1);
  await english.click();
  await page.getByLabel('Цвет преподавателя').fill('#bbddff');
  await expect(english).toHaveCSS('background-color', 'rgb(187, 221, 255)');
  await english.click();
  await page.keyboard.press('Control+c');
  await page.locator(`[data-cell="${3 * periods + 4}:1"]`).click();
  await page.keyboard.press('Control+v');
  await expect(page.locator(`[data-cell="${3 * periods + 4}:1"] .constructor-card`).filter({ hasText: 'Англ' })).toHaveCount(1);
  await page.setViewportSize({ width: 1366, height: 768 });
  await page.locator('[data-cell="0:4"] .constructor-card').first().hover();
  await page.locator('[data-cell="0:4"] .constructor-card').first().click();
  const overlap = await page.locator('[data-cell="0:4"]').evaluate((cell) => {
    const add = cell.querySelector('.constructor-cell-add')?.getBoundingClientRect();
    const cards = [...cell.querySelectorAll('.constructor-card')].map((card) => card.getBoundingClientRect());
    return Boolean(add && cards.some((card) => add.left < card.right && add.right > card.left && add.top < card.bottom && add.bottom > card.top));
  });
  expect(overlap).toBeFalsy();
  await page.screenshot({ path: '.local-test/constructor-1366-100.png' });
  await page.getByRole('combobox', { name: 'Масштаб' }).selectOption('85');
  await page.screenshot({ path: '.local-test/constructor-1366-85.png' });
  await page.getByRole('button', { name: 'Уместить сетку по ширине' }).click();
  await page.screenshot({ path: '.local-test/constructor-1366-fit.png' });
  await page.setViewportSize({ width: 1920, height: 1080 });
  await page.getByRole('group', { name: 'Режим просмотра' }).getByRole('button', { name: 'День' }).click();
  await page.getByRole('button', { name: 'Пятница' }).click();
  await page.locator('[data-cell="4:2"] [data-lesson-id="e2e-event"]').click();
  await expect(page.locator('[data-cell="5:3"] [data-lesson-id="e2e-event"]')).toHaveCount(1);
  await page.screenshot({ path: '.local-test/constructor-event-1920.png' });
});

test('form creates one mixed-class lesson and one multi-slot event that survive reopening', async ({ page }) => {
  const groupsResponse = await page.request.get('http://localhost:8011/api/admin/groups', { headers: { 'X-Dev-Auth': 'admin:1' } });
  const groups = (await groupsResponse.json()).items as { id: string; group_type: string; display_name: string; base_class_name?: string }[];
  const mixed = groups.find((item) => item.display_name === 'E2E Английский 5–6 · A');
  expect(mixed).toBeTruthy();
  await page.goto('/admin/schedule/constructor?role=admin');
  await page.getByRole('button', { name: /Пустая школьная неделя/ }).click();
  await page.locator('[data-cell="0:0"]').click();
  await page.getByRole('button', { name: 'Форма', exact: true }).click();
  await page.getByRole('textbox', { name: 'Предмет нового занятия' }).fill('Английский язык');
  await page.locator('.constructor-create-form').getByRole('button', { name: /Учебные группы/ }).click();
  await page.locator('.constructor-create-form').locator(`input[type="checkbox"][value="${mixed!.id}"]`).check();
  await expect(page.locator('.constructor-create-form')).toContainText('Затронутые классы:');
  await page.getByRole('combobox', { name: 'Преподаватель нового занятия' }).selectOption({ index: 1 });
  await page.getByRole('textbox', { name: 'Кабинет нового занятия' }).fill('17');
  await page.getByRole('button', { name: 'Добавить занятие' }).click();
  const mixedId = await page.locator('[data-cell="0:0"] .constructor-card').getAttribute('data-lesson-id');
  await expect(page.locator(`[data-cell="0:1"] [data-lesson-id="${mixedId}"]`)).toHaveCount(1);
  await page.locator(`[data-cell="0:1"] [data-lesson-id="${mixedId}"]`).click();
  await page.locator('.constructor-inspector').getByRole('combobox', { name: 'Предмет', exact: true }).fill('Английский язык · практика');
  await expect(page.locator(`[data-cell="0:0"] [data-lesson-id="${mixedId}"]`)).toContainText('практика');

  await page.locator('[data-cell="4:2"]').click();
  await page.getByRole('button', { name: 'Событие', exact: true }).click();
  await page.getByRole('textbox', { name: 'Название события' }).fill('Поездка в музей');
  // The seventh-grade column contains several administrative classes, so
  // selecting its cell deliberately does not choose a class on our behalf.
  await page.locator('.constructor-create-form').getByRole('checkbox', { name: '7 класс', exact: true }).check();
  await page.locator('.constructor-create-form').getByRole('checkbox', { name: '8 класс' }).check();
  await page.locator('.constructor-create-form label').filter({ hasText: 'Конец' }).locator('input').fill('14:25');
  await page.locator('.constructor-create-form label').filter({ hasText: 'Место' }).locator('input').fill('Музей');
  await page.locator('.constructor-create-form label').filter({ hasText: 'Формат' }).locator('select').selectOption('offsite');
  await page.locator('.constructor-create-form label').filter({ hasText: 'Описание' }).locator('textarea').fill('Сбор у входа');
  await page.getByRole('listbox', { name: 'Сопровождающие нового события' }).selectOption({ index: 1 });
  await page.getByRole('button', { name: 'Добавить событие' }).click();
  const eventId = await page.locator('[data-cell="4:2"] .constructor-card').getAttribute('data-lesson-id');
  for (const cell of ['4:2', '4:3', '5:2', '5:3']) await expect(page.locator(`[data-cell="${cell}"] [data-lesson-id="${eventId}"]`)).toHaveCount(1);
  await page.getByRole('button', { name: /Сохранить/ }).first().click();
  await expect(page.getByText('Сохранено', { exact: true })).toBeVisible();
  await page.reload();
  await page.getByRole('button', { name: /Новый шаблон/ }).first().click();
  await expect(page.locator(`[data-cell="0:0"] [data-lesson-id="${mixedId}"]`)).toHaveCount(1);
  await expect(page.locator(`[data-cell="5:3"] [data-lesson-id="${eventId}"]`)).toHaveCount(1);
  await page.locator(`[data-cell="4:2"] [data-lesson-id="${eventId}"]`).click();
  await expect(page.locator('.constructor-event-fields textarea')).toHaveValue('Сбор у входа');
  await expect(page.locator('.constructor-event-fields select').first()).toHaveValue('offsite');
});
